def cases():
    with open(CASES_CSV, newline="") as f:
        return {r["case"]: r for r in csv.DictReader(f)}


def history(path):
    if not path.exists():
        return None
    with open(path, newline="") as f:
        rows = [{k: float(v) for k, v in r.items()} for r in csv.DictReader(f)]
    return rows if len(rows) > 1 else None


def run(case):
    h = history(RES / case / "history.csv")
    s = RES / case / "summary.json"
    return (h, json.loads(s.read_text())) if h and s.exists() else (None, None)


def final_R(h):
    return h[-1]["c_cavity"]


def rel(a, b):
    return abs(a - b) / abs(b) if b else float("inf")


# ---------------------------------------------------------------- verification
def balance(h, p):
    """Fluid and contaminant balances from the sampled history (per unit depth)."""
    mesh = p.get("mesh") or {}
    W, D, H = p["W"], p["W"] * p["AR"], p["H"]
    area = (mesh.get("Lu", 2 * W) + W + mesh.get("Ld", 3 * W)) * H + W * D
    mdots = [k for k in h[0] if k.startswith("mdot_")]
    outs = [k[2:] for k in h[0] if k.startswith("y_") and f"mdot_{k[2:]}" in h[0]]   # outflow boundaries
    scale = [max(sum(abs(r[k]) for k in mdots) / 2, 1e-30) for r in h]              # total through-flow
    imb = max(abs(sum(r[k] for k in mdots)) / sc for r, sc in zip(h[1:], scale[1:]))
    m0 = RHO * W * D                                   # cavity full at mass fraction 1
    m_dom = [RHO * area * r["c_domain"] for r in h]
    out_int, removed = 0.0, []

    def flux(r):   # contaminant leaving through every outflow boundary (outflow counted positive)
        return sum(max(r[f"mdot_{b}"], 0.0) * r[f"y_{b}"] for b in outs)

    for a, b in zip(h, h[1:]):                         # trapezoid on the sampled outflow
        fa, fb = flux(a), flux(b)
        out_int += 0.5 * (fa + fb) * (b["time_s"] - a["time_s"])
        removed.append((m0 - RHO * area * b["c_domain"], out_int))
    lost, flowed = removed[-1]
    return dict(mass_imbalance_max=imb, initial_inventory_error=rel(m_dom[0], m0),
                y_min=min(r["y_min"] for r in h), y_max=max(r["y_max"] for r in h),
                contaminant_balance_error=rel(flowed, lost) if lost > 0 else float("nan"))


def verification(cs):
    lines = ["# Verification report", "", f"Generated by analyze.py. Model label: {LABEL}.", ""]

    lines += ["## 1. Baseline reproduction (Case A vs 3d_nand/ansys_busnaina fig4_f200k)", ""]
    a, _ = run("A0_ar1_osc200k")          # exact original mesh (no trench split)
    b = history(BASELINE_RESULTS / "fig4_f200k" / "history.csv")
    s, _ = run("A_ar1_osc200k")           # same physics with the split trench: must agree with A0
    if a and s:
        lines.append(f"- split vs unsplit trench (report zones only): final C/C0 {final_R(s):.5f} vs "
                     f"{final_R(a):.5f}, difference {100 * rel(final_R(s), final_R(a)):.3f} %")
    if a and b:
        lines.append(f"- final C/C0: new {final_R(a):.5f}, original {final_R(b):.5f}, "
                     f"difference {100 * rel(final_R(a), final_R(b)):.2f} %")
    else:
        lines.append("- not available (needs both runs; the original lives in ../3d_nand)")

    lines += ["", "## 2. Zero transverse amplitude (lambda = 0, top as velocity inlet) vs Case A", ""]
    for g in ("ar1", "ar5"):
        for rinse in ("steady", "osc200k"):
            a, _ = run(f"A_{g}_{rinse}")
            z, _ = run(f"B_{g}_{rinse}_v0")
            if a and z:
                lines.append(f"- {g} {rinse}: final C/C0 A {final_R(a):.5f}, lambda=0 {final_R(z):.5f}, "
                             f"difference {100 * rel(final_R(z), final_R(a)):.2f} % "
                             "(effect of replacing the symmetry top by a u = U velocity inlet)")

    lines += ["", "## 3-5. Mass balance, concentration bounds, contaminant balance (every finished case)", "",
              "| case | max fluid imbalance / outflow | initial inventory error | Y min | Y max | contaminant balance error |",
              "|---|---|---|---|---|---|"]
    for name in cs:
        h, p = run(name)
        if not h or not any(k.startswith("mdot_") for k in h[0]):
            continue
        bl = balance(h, p)
        lines.append(f"| {name} | {bl['mass_imbalance_max']:.1e} | {bl['initial_inventory_error']:.1e} | "
                     f"{bl['y_min']:.1e} | {bl['y_max']:.4f} | {bl['contaminant_balance_error']:.1e} |")
    lines += ["", "Contaminant balance uses the 200 sampled points (trapezoid), so it is approximate for "
              "pulsed flow; the per-time-step reports are in results/<case>/reports.out. "
              "Y outside [0, 1] beyond ~1e-3 indicates numerical over/undershoot."]

    lines += ["", "## 6. Time-step and mesh sensitivity (B_ar5_osc200k_v0.5)", ""]
    ref, _ = run("B_ar5_osc200k_v0.5")
    for name, what in (("V_ar5_osc200k_v0.5_dt", "time step halved"), ("V_ar5_osc200k_v0.5_n80", "mesh doubled")):
        v, _ = run(name)
        if ref and v:
            lines.append(f"- {what}: final C/C0 {final_R(v):.5f} vs {final_R(ref):.5f} "
                         f"({100 * rel(final_R(v), final_R(ref)):.1f} %)")
    (OUT / "verification.md").write_text("\n".join(lines) + "\n")
    print("wrote", OUT / "verification.md")


