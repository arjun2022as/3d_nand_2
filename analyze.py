ANGLE_METRICS = (   # (key, label, larger is better)
    ("eta", "Cleaning efficiency at t_end (%)", True),
    ("eta_deep", "Lower-half trench cleaned at t_end (%)", True),
    ("sh", "Mean trench Sherwood number", True),
    ("u_cav", "Mean speed inside trench (m/s)", True),
    ("u_deep", "Mean speed in lower half (m/s)", True),
    ("segregation", "Peak / mean concentration in trench (1 = uniform)", False),
)


def angle_metrics(h, p):
    """Mixing metrics of one run: removal, deep removal, exchange rate, stirring, uniformity."""
    t = [x["time_s"] for x in h]
    R = [x["c_cavity"] for x in h]
    sh = sherwood(t, R, p["W"] * p["AR"], p["W"])

    def tavg(key):   # time average over the run (trapezoid)
        v = [x[key] for x in h]
        return sum(0.5 * (v[i] + v[i + 1]) * (t[i + 1] - t[i]) for i in range(len(t) - 1)) / (t[-1] - t[0])

    seg = [x["y_max_cav"] / x["c_cavity"] for x in h if x["c_cavity"] > 1e-12]
    return dict(eta=100 * (1 - R[-1]),
                eta_deep=100 * (1 - h[-1]["c_deep"]) if "c_deep" in h[-1] else float("nan"),
                sh=sum(v for _, v in sh) / len(sh) if sh else float("nan"),
                u_cav=tavg("u_cav") if "u_cav" in h[0] else float("nan"),
                u_deep=tavg("u_deep") if "u_deep" in h[0] else float("nan"),
                segregation=sum(seg) / len(seg) if seg else float("nan"))


def optimum(angles, values, maximize=True):
    """Best sampled angle and a parabola-refined estimate through it and its two neighbours."""
    pts = [(a, v) for a, v in zip(angles, values) if v == v]
    if len(pts) < 3:
        return None, None
    pts.sort()
    i = max(range(len(pts)), key=lambda k: pts[k][1] if maximize else -pts[k][1])
    best = pts[i][0]
    if 0 < i < len(pts) - 1:
        (a0, v0), (a1, v1), (a2, v2) = pts[i - 1], pts[i], pts[i + 1]
        den = (a0 - a1) * (a0 - a2) * (a1 - a2)
        A = (a2 * (v1 - v0) + a1 * (v0 - v2) + a0 * (v2 - v1)) / den
        B = (a2 * a2 * (v0 - v1) + a1 * a1 * (v2 - v0) + a0 * a0 * (v1 - v2)) / den
        if A != 0:
            return best, min(max(-B / (2 * A), a0), a2)
    return best, float(best)    # optimum at an end of the sweep: no interior estimate


def angle_sweep(cs, plt):
    """Case R: every mixing metric vs stream angle, per geometry, with the optimum angle."""
    series = {}
    for name, r in cs.items():
        if r["family"] != "R":
            continue
        h, p = run(name)
        if h:
            series.setdefault(name.rsplit("_a", 1)[0], []).append((float(r["angle_deg"]), angle_metrics(h, p)))
    if not series:
        return
    fig, axes = plt.subplots(2, 3, figsize=(15, 8.5))
    rows, best_rows = [], []
    for geom, pts in sorted(series.items()):
        pts.sort(key=lambda x: x[0])
        angles = [a for a, _ in pts]
        for ax, (key, lab, big) in zip(axes.flat, ANGLE_METRICS):
            vals = [m[key] for _, m in pts]
            if all(v != v for v in vals):
                continue
            line, = ax.plot(angles, vals, "o-", label=geom.replace("R_", ""))
            best, est = optimum(angles, vals, big)
            if best is not None:
                ax.axvline(est, color=line.get_color(), ls=":", lw=1)
                best_rows.append((geom, key, best, round(est, 1)))
            ax.set(xlabel="Stream angle from wafer (deg)", ylabel=lab, xticks=range(0, 91, 15))
            if key in ("u_cav", "u_deep", "sh"):
                ax.set_yscale("log")
        rows += [(geom, a, *[m[k] for k, _, _ in ANGLE_METRICS]) for a, m in pts]
    axes.flat[0].legend(fontsize=8)
    fig.suptitle("Case R: same speed, stream rotated from parallel (0 deg) to normal (90 deg); "
                 "dotted = estimated optimum. Imposed flow, not an acoustic calculation.", fontsize=10)
    save(fig, "angle_sweep", ["geometry", "angle_deg"] + [k for k, _, _ in ANGLE_METRICS], rows)
    with open(OUT / "angle_optimum.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["geometry", "metric", "best_sampled_angle_deg", "parabola_estimate_deg"])
        w.writerows(best_rows)
    print("\noptimum stream angle (best sampled / parabola estimate):")
    for g, k, b, e in best_rows:
        print(f"  {g:28s} {k:12s} {b:5.0f} / {e:5.1f} deg")


def metrics_of(name):
    h, p = run(name)
    return angle_metrics(h, p) if h else None


def flow_type_comparison(cs, plt):
    """One trench, one pulse frequency (200 kHz): U only vs every V variant vs best stream angle."""
    for g in ("ar1", "ar5"):
        groups = [
            ("U only, steady", f"A_{g}_steady"),
            ("U only, pulsed 200 kHz", f"A_{g}_osc200k"),
            ("U steady + V steady (27 deg)", f"B_{g}_steady_v0.5"),
            ("U pulsed + V steady", f"B_{g}_osc200k_v0.5"),
            ("V = 0.5 U(t) (27 deg)", f"Bf_{g}_osc200k_v0.5"),
            ("U pulsed + V pulsed, in phase", f"C_{g}_osc200k_vp200k_ph0"),
            ("U pulsed + V pulsed, anti-phase", f"C_{g}_osc200k_vp200k_ph180"),
            ("U pulsed + V pulsed 20 kHz", f"C_{g}_osc200k_vp20k_ph0"),
        ]
        for rinse, lab in (("steady", "steady"), ("osc200k", "pulsed")):      # best angle of the rotation
            best = None
            for name in cs:
                if name.startswith(f"R_w1um_{g}_{rinse}_a"):
                    m = metrics_of(name)
                    if m and (best is None or m["eta"] > best[1]["eta"]):
                        best = (name, m)
            if best:
                groups.append((f"same speed tilted to {best[0][-2:]} deg ({lab}, best)", best[0]))
        data = [(lab, name, metrics_of(name)) for lab, name in groups]
        data = [d for d in data if d[2]]
        if len(data) < 2:
            continue
        keys = [k for k in ANGLE_METRICS if k[0] != "u_cav"]
        fig, axes = plt.subplots(1, len(keys), figsize=(4.2 * len(keys), 5.6), sharey=True)
        ypos = list(range(len(data)))
        for ax, (key, lab, big) in zip(axes, keys):
            vals = [d[2][key] for d in data]
            ref = vals[0]
            colors = ["0.55" if i < 2 else ("tab:green" if (v > ref) == big else "tab:red")
                      for i, v in enumerate(vals)]
            ax.barh(ypos, vals, color=colors)
            ax.set(xlabel=lab)
            if key in ("sh", "u_deep"):
                ax.set_xscale("log")
            ax.title.set_fontsize(9)
        axes[0].set_yticks(ypos, [d[0] for d in data], fontsize=8)
        axes[0].invert_yaxis()
        fig.suptitle(f"Mixing comparison, W = 1 um, AR {g[2:]}, rinse 200 kHz where pulsed. Grey: U only; "
                     f"green/red: better/worse than U-only steady.\n{LABEL}", fontsize=10)
        save(fig, f"flow_type_comparison_{g}", ["label", "case"] + [k for k, _, _ in ANGLE_METRICS],
             [(d[0], d[1], *[d[2][k] for k, _, _ in ANGLE_METRICS]) for d in data])


def angle_comparison(cs, plt):
    """Same angles two ways: V proportional to U (U kept, flow added) vs constant-speed rotation."""
    for g in ("ar1", "ar5"):
        series = {
            "V = tan(phi) U, steady (flow added)": [(0, f"B_{g}_steady_v0")] +
            [(a, f"B_{g}_steady_a{a:02d}") for a in (15, 30, 60, 75)] + [(45, f"B_{g}_steady_v1")],
            "V = tan(phi) U(t), pulsed (flow added)": [(0, f"B_{g}_osc200k_v0")] +
            [(a, f"Bf_{g}_osc200k_a{a:02d}") for a in (15, 30, 60, 75)] + [(45, f"Bf_{g}_osc200k_v1")],
            "same speed tilted, steady": [(a, f"R_w1um_{g}_steady_a{a:02d}") for a in range(0, 91, 15)],
            "same speed tilted, pulsed": [(a, f"R_w1um_{g}_osc200k_a{a:02d}") for a in range(0, 91, 15)],
        }
        keys = [k for k in ANGLE_METRICS if k[0] in ("eta", "eta_deep", "sh", "u_deep")]
        fig, axes = plt.subplots(1, 4, figsize=(18, 4.6))
        rows = []
        for label, pts in series.items():
            got = sorted((a, metrics_of(n)) for a, n in pts if metrics_of(n))
            if not got:
                continue
            for ax, (key, lab, _) in zip(axes, keys):
                ax.plot([a for a, _ in got], [m[key] for _, m in got], "o-" if "steady" in label else "s--",
                        label=label)
            rows += [(label, a, *[m[k] for k, _, _ in ANGLE_METRICS]) for a, m in got]
        if not rows:
            plt.close(fig)
            continue
        for ref, style in ((f"A_{g}_steady", ":"), (f"A_{g}_osc200k", "-.")):
            m = metrics_of(ref)
            if m:
                for ax, (key, _, _) in zip(axes, keys):
                    ax.axhline(m[key], color="black", ls=style, lw=1,
                               label=f"U only, {'steady' if 'steady' in ref else 'pulsed'}")
        for ax, (key, lab, _) in zip(axes, keys):
            ax.set(xlabel="Flow angle from wafer (deg)", ylabel=lab, xticks=range(0, 91, 15))
            if key in ("sh", "u_deep"):
                ax.set_yscale("log")
        axes[0].legend(fontsize=7)
        fig.suptitle(f"Flow angle two ways, W = 1 um, AR {g[2:]}: adding V to the rinse vs tilting at the "
                     f"same speed. {LABEL}", fontsize=10)
        save(fig, f"angle_comparison_{g}", ["series", "angle_deg"] + [k for k, _, _ in ANGLE_METRICS], rows)


def save(fig, name, header, rows):
    fig.tight_layout()
    fig.savefig(OUT / f"{name}.png", dpi=150)
    with open(OUT / f"{name}.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)
    print("wrote", OUT / f"{name}.png", "+ .csv")
    fig.clf()


def main():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    OUT.mkdir(parents=True, exist_ok=True)
    cs = cases()
    figures(cs, plt)
    angle_sweep(cs, plt)
    flow_type_comparison(cs, plt)
    angle_comparison(cs, plt)
    verification(cs)


if __name__ == "__main__":
    main()
