#!/usr/bin/env python3
"""Comparison figures, data tables and verification report for the transverse-exchange study.

    python analyze.py            # needs matplotlib (the pyfluent241 venv has it); no Fluent
Writes results/analysis/: *.png, the CSV behind every figure, and verification.md.
Results of the imposed-flow model (Cases B/C) are labelled as such; there are no acoustic results yet.
"""
import csv
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from trenchflow.physics import CASES_CSV, RHO, plan, sherwood  # noqa: E402

RES = HERE / "results"
OUT = RES / "analysis"
BASELINE_RESULTS = HERE.parent / "3d_nand" / "ansys_busnaina" / "results"
LABEL = "imposed transverse inflow (Cases B/C) - not an acoustic calculation"


def cases():
    with open(CASES_CSV, newline="") as f:
        return {r["case"]: r for r in csv.DictReader(f)}


def history(path):
    if not path.exists():
        return None
    with open(path, newline="") as f:
        rows = [{k: float(v) for k, v in r.items()} for r in csv.DictReader(f)]
    return rows if len(rows) > 1 else None


def run(case):
    h = history(RES / case / "history.csv")
    s = RES / case / "summary.json"
    return (h, json.loads(s.read_text())) if h and s.exists() else (None, None)


def final_R(h):
    return h[-1]["c_cavity"]


def rel(a, b):
    return abs(a - b) / abs(b) if b else float("inf")


# ---------------------------------------------------------------- verification
def balance(h, p):
    """Fluid and contaminant balances from the sampled history (per unit depth)."""
    mesh = p.get("mesh") or {}
    W, D, H = p["W"], p["W"] * p["AR"], p["H"]
    area = (mesh.get("Lu", 2 * W) + W + mesh.get("Ld", 3 * W)) * H + W * D
    mdots = [k for k in h[0] if k.startswith("mdot_")]
    imb = max(abs(sum(r[k] for k in mdots)) / max(abs(r["mdot_outlet"]), 1e-30) for r in h[1:])
    m0 = RHO * W * D                                   # cavity full at mass fraction 1
    m_dom = [RHO * area * r["c_domain"] for r in h]
    out_int, removed = 0.0, []
    for a, b in zip(h, h[1:]):                         # trapezoid on the sampled outflow
        fa, fb = a["mdot_outlet"] * a["y_outlet"], b["mdot_outlet"] * b["y_outlet"]
        out_int += 0.5 * (fa + fb) * (b["time_s"] - a["time_s"])
        removed.append((m0 - RHO * area * b["c_domain"], out_int))
    lost, flowed = removed[-1]
    return dict(mass_imbalance_max=imb, initial_inventory_error=rel(m_dom[0], m0),
                y_min=min(r["y_min"] for r in h), y_max=max(r["y_max"] for r in h),
                contaminant_balance_error=rel(flowed, lost) if lost > 0 else float("nan"))


def verification(cs):
    lines = ["# Verification report", "", f"Generated by analyze.py. Model label: {LABEL}.", ""]

    lines += ["## 1. Baseline reproduction (Case A vs 3d_nand/ansys_busnaina fig4_f200k)", ""]
    a, _ = run("A_ar1_osc200k")
    b = history(BASELINE_RESULTS / "fig4_f200k" / "history.csv")
    if a and b:
        lines.append(f"- final C/C0: new {final_R(a):.5f}, original {final_R(b):.5f}, "
                     f"difference {100 * rel(final_R(a), final_R(b)):.2f} %")
    else:
        lines.append("- not available (needs both runs; the original lives in ../3d_nand)")

    lines += ["", "## 2. Zero transverse amplitude (lambda = 0, top as velocity inlet) vs Case A", ""]
    for g in ("ar1", "ar5"):
        for rinse in ("steady", "osc200k"):
            a, _ = run(f"A_{g}_{rinse}")
            z, _ = run(f"B_{g}_{rinse}_v0")
            if a and z:
                lines.append(f"- {g} {rinse}: final C/C0 A {final_R(a):.5f}, lambda=0 {final_R(z):.5f}, "
                             f"difference {100 * rel(final_R(z), final_R(a)):.2f} % "
                             "(effect of replacing the symmetry top by a u = U velocity inlet)")

    lines += ["", "## 3-5. Mass balance, concentration bounds, contaminant balance (every finished case)", "",
              "| case | max fluid imbalance / outflow | initial inventory error | Y min | Y max | contaminant balance error |",
              "|---|---|---|---|---|---|"]
    for name in cs:
        h, p = run(name)
        if not h or "mdot_outlet" not in h[0]:
            continue
        bl = balance(h, p)
        lines.append(f"| {name} | {bl['mass_imbalance_max']:.1e} | {bl['initial_inventory_error']:.1e} | "
                     f"{bl['y_min']:.1e} | {bl['y_max']:.4f} | {bl['contaminant_balance_error']:.1e} |")
    lines += ["", "Contaminant balance uses the 200 sampled points (trapezoid), so it is approximate for "
              "pulsed flow; the per-time-step reports are in results/<case>/reports.out. "
              "Y outside [0, 1] beyond ~1e-3 indicates numerical over/undershoot."]

    lines += ["", "## 6. Time-step and mesh sensitivity (B_ar5_osc200k_v0.5)", ""]
    ref, _ = run("B_ar5_osc200k_v0.5")
    for name, what in (("V_ar5_osc200k_v0.5_dt", "time step halved"), ("V_ar5_osc200k_v0.5_n80", "mesh doubled")):
        v, _ = run(name)
        if ref and v:
            lines.append(f"- {what}: final C/C0 {final_R(v):.5f} vs {final_R(ref):.5f} "
                         f"({100 * rel(final_R(v), final_R(ref)):.1f} %)")
    (OUT / "verification.md").write_text("\n".join(lines) + "\n")
    print("wrote", OUT / "verification.md")


# ---------------------------------------------------------------- figures
def figures(cs, plt):
    # (1) C/C0 vs time: baseline and transverse cases, per geometry and rinse
    for g in ("ar1", "ar5"):
        for rinse in ("steady", "osc200k"):
            fig, ax = plt.subplots(figsize=(6.5, 4.6))
            rows = []
            for name, r in cs.items():
                if r["family"] not in ("A", "B") or not name.startswith(f"{r['family']}_{g}_{rinse}"):
                    continue
                h, _ = run(name)
                if not h:
                    continue
                lab = "A: baseline (v = 0)" if r["family"] == "A" else f"B: V/u_avg = {float(r['v_ratio']):g}"
                ax.semilogy([x["time_s"] * 1e3 for x in h], [x["c_cavity"] for x in h], label=lab,
                            lw=2.5 if r["family"] == "A" else 1.4, color="black" if r["family"] == "A" else None)
                rows += [(name, x["time_s"], x["c_cavity"]) for x in h]
            if not rows:
                plt.close(fig)
                continue
            ax.set(xlabel="Time (ms)", ylabel="C/C0 in trench",
                   title=f"W = 1 um, AR {g[2:]}, {rinse} rinse\n{LABEL}")
            ax.title.set_fontsize(9)
            ax.legend(fontsize=7)
            save(fig, f"R_vs_time_{g}_{rinse}", ["case", "time_s", "C/C0"], rows)

    # (2) final cleaning efficiency and mean Sherwood number vs V/u_avg
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4.4))
    rows = []
    for g in ("ar1", "ar5"):
        for rinse in ("steady", "osc200k"):
            pts = []
            for name, r in cs.items():
                if name.startswith(f"B_{g}_{rinse}_v"):
                    h, p = run(name)
                    if h:
                        t = [x["time_s"] for x in h]
                        R = [x["c_cavity"] for x in h]
                        sh = sherwood(t, R, p["W"] * p["AR"], p["W"])
                        mean_sh = sum(v for _, v in sh) / len(sh)
                        pts.append((float(r["v_ratio"]), 100 * (1 - R[-1]), mean_sh))
            a, pa = run(f"A_{g}_{rinse}")
            if not pts:
                continue
            pts.sort()
            lam, eta, sh = zip(*pts)
            line, = ax1.plot(lam, eta, "o-", label=f"AR {g[2:]}, {rinse}")
            ax2.plot(lam, sh, "o-", color=line.get_color(), label=f"AR {g[2:]}, {rinse}")
            if a:
                ax1.axhline(100 * (1 - final_R(a)), ls=":", color=line.get_color())
            rows += [(g, rinse, *x) for x in pts]
    if rows:
        ax1.set(xlabel="V / u_avg  (flow approach angle atan(V/U))", ylabel="Cleaning efficiency at 0.4 ms (%)",
                title="Dotted: Case A baseline")
        ax2.set(xlabel="V / u_avg", ylabel="Mean trench Sherwood number", yscale="log")
        ax1.legend(fontsize=7)
        fig.suptitle(LABEL, fontsize=9)
        save(fig, "eta_vs_V", ["geometry", "rinse", "V_over_u", "eta_percent", "mean_Sh"], rows)
    else:
        plt.close(fig)

    # (3) Case C: pulsed V phase/frequency vs steady V of the same mean
    fig, ax = plt.subplots(figsize=(7.5, 4.4))
    rows = []
    for g in ("ar1", "ar5"):
        for name, lab in ((f"A_{g}_osc200k", "A baseline"), (f"B_{g}_osc200k_v0.5", "B steady V"),
                          (f"Bf_{g}_osc200k_v0.5", "Bf V = 0.5 U(t)"),
                          (f"C_{g}_osc200k_vp200k_ph0", "C pulsed, in phase"),
                          (f"C_{g}_osc200k_vp200k_ph180", "C pulsed, anti-phase"),
                          (f"C_{g}_osc200k_vp20k_ph0", "C pulsed 20 kHz")):
            h, _ = run(name)
            if h:
                rows.append((g, lab, name, 100 * final_R(h)))
    if rows:
        for g, off in (("ar1", -0.2), ("ar5", 0.2)):
            sel = [r for r in rows if r[0] == g]
            ax.bar([i + off for i in range(len(sel))], [r[3] for r in sel], width=0.4, label=f"AR {g[2:]}")
        labels = list(dict.fromkeys(r[1] for r in rows))
        ax.set_xticks(range(len(labels)), labels, rotation=20, fontsize=8)
        ax.set(ylabel="Contaminant left at 0.4 ms (%)", title=f"Mean V = 0.5 u_avg, rinse 200 kHz\n{LABEL}")
        ax.title.set_fontsize(9)
        ax.legend(fontsize=8)
        save(fig, "case_C_comparison", ["geometry", "label", "case", "contaminant_left_percent"], rows)
    else:
        plt.close(fig)


def save(fig, name, header, rows):
    fig.tight_layout()
    fig.savefig(OUT / f"{name}.png", dpi=150)
    with open(OUT / f"{name}.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)
    print("wrote", OUT / f"{name}.png", "+ .csv")
    fig.clf()


def main():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    OUT.mkdir(parents=True, exist_ok=True)
    cs = cases()
    figures(cs, plt)
    verification(cs)


if __name__ == "__main__":
    main()
